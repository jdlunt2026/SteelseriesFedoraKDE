"""udev rules SteelPanel needs (installed with ``sudo steelpanel --install-udev``)."""

from __future__ import annotations

RULES_PATH = "/etc/udev/rules.d/70-steelpanel.rules"


def remap_product_ids() -> list[int]:
    """Mice that use software remapping (no onboard mapping in rivalcfg)."""
    from rivalcfg import devices

    return sorted({pid for (vid, pid), prof in devices.PROFILES.items()
                   if vid == 0x1038 and "buttons_mapping" not in prof["settings"]})


def generate_rules() -> str:
    # "uaccess" gives the logged-in desktop user access; it must run before
    # 73-seat-late.rules, hence the 70- prefix.
    lines = [
        "# Generated by SteelPanel: software button remapping.",
        "# Input devices of SteelSeries mice without onboard remapping support:",
    ]
    lines += [
        f'SUBSYSTEM=="input", ATTRS{{idVendor}}=="1038", ATTRS{{idProduct}}=="{pid:04x}", TAG+="uaccess"'
        for pid in remap_product_ids()
    ]
    lines += [
        "# Virtual input device used to send the remapped buttons:",
        'KERNEL=="uinput", SUBSYSTEM=="misc", TAG+="uaccess", OPTIONS+="static_node=uinput"',
        "",
    ]
    return "\n".join(lines)


def write_rules(path: str = RULES_PATH) -> None:
    with open(path, "w") as f:
        f.write(generate_rules())
