"""udev rules SteelPanel needs (installed with ``sudo steelpanel --install-udev``)."""

from __future__ import annotations

RULES_PATH = "/etc/udev/rules.d/70-steelpanel.rules"


def input_product_ids() -> list[int]:
    """Mice whose input SteelPanel may filter (angle snapping is offered for
    all of them, software remapping for those without onboard mapping)."""
    from rivalcfg import devices

    return sorted({pid for (vid, pid) in devices.PROFILES if vid == 0x1038})


def generate_rules() -> str:
    # "uaccess" gives the logged-in desktop user access; it must run before
    # 73-seat-late.rules, hence the 70- prefix.
    lines = [
        "# Generated by SteelPanel: software button remapping and angle snapping.",
        "# Input devices of SteelSeries mice:",
    ]
    lines += [
        f'SUBSYSTEM=="input", ATTRS{{idVendor}}=="1038", ATTRS{{idProduct}}=="{pid:04x}", TAG+="uaccess"'
        for pid in input_product_ids()
    ]
    lines += [
        "# Virtual input device used to send the filtered input:",
        'KERNEL=="uinput", SUBSYSTEM=="misc", TAG+="uaccess", OPTIONS+="static_node=uinput"',
        "",
    ]
    return "\n".join(lines)


def write_rules(path: str = RULES_PATH) -> None:
    with open(path, "w") as f:
        f.write(generate_rules())
